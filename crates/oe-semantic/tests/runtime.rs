#[test]
#[ignore = "requires the explicitly installed external Python runtime; run separately as a native identity-boundary fixture"]
fn real_python_poisoned_timestamp_pyc_is_not_executed_by_the_identity_probe() {
    use std::process::Command;
    let fixture = Fixture::new();
    let (_, identity) = fixture.wheel();
    let bootstrap = root().join(if cfg!(windows) {
        "runtime/.venv/Scripts/python.exe"
    } else {
        "runtime/.venv/bin/python"
    });
    assert!(
        bootstrap.is_file(),
        "install the selected external Python runtime first"
    );
    let environment = fixture.scratch.0.join("external-python");
    let result = Command::new(&bootstrap)
        .args(["-I", "-B", "-m", "venv", "--without-pip"])
        .arg(&environment)
        .output()
        .unwrap();
    assert!(
        result.status.success(),
        "external fixture venv creation failed"
    );
    let python = environment.join(if cfg!(windows) {
        "Scripts/python.exe"
    } else {
        "bin/python"
    });
    let result = Command::new(&python)
        .args([
            "-I",
            "-B",
            "-c",
            "import sysconfig; print(sysconfig.get_paths()['purelib'])",
        ])
        .output()
        .unwrap();
    assert!(result.status.success());
    let site = PathBuf::from(String::from_utf8(result.stdout).unwrap().trim());
    assert!(site.starts_with(&fixture.scratch.0));
    for (name, bytes) in &fixture.payload {
        let path = site.join(name);
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, bytes).unwrap();
    }
    fs::write(
        site.join(DIST).join("direct_url.json"),
        json!({"archive_info":{"hashes":{"sha256":identity.artifact_sha256}}}).to_string(),
    )
    .unwrap();
    let source = site.join("semantica/__init__.py");
    let marker = fixture.scratch.0.join("poison-was-executed");
    // Build a malicious timestamp-valid pyc, then restore every source byte.
    // This is a synthetic external interpreter fixture, not an OE Python bridge.
    let poison = r#"import importlib.util, pathlib, py_compile, struct, sys
source = pathlib.Path(sys.argv[1])
marker = pathlib.Path(sys.argv[2])
payload = source.read_bytes()
stat = source.stat()
code = payload.decode() + '\nfrom pathlib import Path\nPath(' + repr(str(marker)) + ').write_text("cached code executed")\n'
source.write_text(code)
cached = pathlib.Path(py_compile.compile(str(source), doraise=True, invalidation_mode=py_compile.PycInvalidationMode.TIMESTAMP))
source.write_bytes(payload)
header = bytearray(cached.read_bytes())
header[8:12] = struct.pack('<I', int(source.stat().st_mtime) & 0xffffffff)
header[12:16] = struct.pack('<I', len(payload))
cached.write_bytes(header)
"#;
    let result = Command::new(&python)
        .args(["-I", "-B", "-c", poison])
        .arg(&source)
        .arg(&marker)
        .output()
        .unwrap();
    assert!(
        result.status.success(),
        "could not prepare timestamp-valid poisoned pyc"
    );
    let old = Command::new(&python)
        .args(["-I", "-B", "-c", "import semantica"])
        .current_dir(&fixture.scratch.0)
        .output()
        .unwrap();
    assert!(old.status.success());
    assert!(
        marker.is_file(),
        "old -I -B must reproduce bytecode execution"
    );
    fs::remove_file(&marker).unwrap();
    assert_eq!(fs::read(&source).unwrap(), INIT);
    let proof = verify_runtime_source_identity(&fixture.scratch.0, None, &python).unwrap();
    assert_eq!(proof.record_files, 3);
    assert_eq!(proof.semantic_execution, "not_run");
    assert!(
        !marker.exists(),
        "identity probe executed unverified old bytecode"
    );
    let private = fixture.scratch.0.join("var");
    if private.exists() {
        assert!(!fs::read_dir(private).unwrap().any(|e| {
            e.unwrap()
                .file_name()
                .to_string_lossy()
                .starts_with("runtime-identity-probe-cache-")
        }));
    }
}
