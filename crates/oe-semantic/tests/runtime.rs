#[test]
fn staging_descriptor_is_exact_and_never_reads_the_formal_lock() {
    let fixture = Fixture::new();
    let (path, identity) = fixture.wheel();
    let dir = fixture.scratch.0.join("staging");
    fs::create_dir(&dir).unwrap();
    fs::copy(path, dir.join(WHEEL)).unwrap();
    let descriptor = dir.join("runtime.json");
    let value = json!({"$schema":STAGING_RUNTIME_SCHEMA,"commit":identity.commit,"version":identity.version,"wheel_filename":WHEEL,"wheel_sha256":identity.artifact_sha256});
    fs::write(&descriptor, value.to_string()).unwrap();
    let proof = read_staging_runtime_descriptor(&descriptor).unwrap();
    assert_eq!(proof.as_runtime_source_lock(), identity);
    assert_eq!(
        proof.descriptor_sha256,
        digest(fs::read(&descriptor).unwrap())
    );
    for key in ["extra", "wheel_filename", "wheel_sha256"] {
        let mut changed = value.clone();
        changed[key] = if key == "wheel_filename" {
            json!("../escape.whl")
        } else {
            json!("invalid")
        };
        fs::write(&descriptor, changed.to_string()).unwrap();
        assert!(
            read_staging_runtime_descriptor(&descriptor).is_err(),
            "{key}"
        );
    }
    // This reader has no formal-root argument and cannot consult/update one.
}

